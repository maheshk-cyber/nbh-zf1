#!/usr/bin/env bash
#
# Regenerate the measured snapshot inside PORTING.md.
#
# Any agent or human can run this at the end of a batch to keep the ledger
# honest. Numbers in PORTING.md are never hand-edited.
#
# Usage:
#   tools/port-status.sh            # fast checks (syntax + phpcs)
#   tools/port-status.sh --smoke    # also run the slow class-load sweep (~7 min)

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

TARGET_VERSION="${TARGET_VERSION:-8.1-8.5}"
LEDGER="PORTING.md"

# ---------------------------------------------------------------- measurements

branch="$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo '?')"
head_sha="$(git rev-parse --short HEAD 2>/dev/null || echo '?')"
head_subject="$(git log -1 --format=%s 2>/dev/null || echo '?')"
dirty="$(git status --porcelain 2>/dev/null | wc -l | tr -d ' ')"

file_count="$(find library -type f -name '*.php' | wc -l | tr -d ' ')"

echo "== syntax check ($file_count files) ==" >&2
# `php -l` also emits deprecation notices for the files it includes; only a
# genuine parse/compile failure counts here.
syntax_failures="$(
  find library -type f -name '*.php' -print0 \
    | xargs -0 -n1 -P8 php -l 2>&1 \
    | grep -cE 'Errors parsing|Parse error|Fatal error' || true
)"

echo "== PHPCompatibility $TARGET_VERSION ==" >&2
vendor/bin/phpcs library \
  --standard=PHPCompatibility \
  --runtime-set testVersion "$TARGET_VERSION" \
  --report=csv > /tmp/port-status.csv 2>/dev/null || true

read -r errors warnings total <<< "$(
  python3 - <<'PY'
import csv
rows = list(csv.reader(open('/tmp/port-status.csv')))[1:]
errs = sum(1 for r in rows if len(r) > 5 and r[3].strip() == 'error')
warns = sum(1 for r in rows if len(r) > 5 and r[3].strip() == 'warning')
print(errs, warns, len(rows))
PY
)"

top_sniffs="$(
  python3 - <<'PY'
import csv, collections
rows = list(csv.reader(open('/tmp/port-status.csv')))[1:]
c = collections.Counter()
kind = {}
for r in rows:
    if len(r) < 6:
        continue
    src = r[5].strip()
    c[src] += 1
    kind[src] = r[3].strip()
lines = []
for src, n in c.most_common(12):
    short = src.replace('PHPCompatibility.', '')
    lines.append(f'| {n} | {kind[src]} | `{short}` |')
print('\n'.join(lines))
PY
)"

smoke_block=""
if [[ "${1:-}" == "--smoke" ]]; then
  echo "== class-load smoke sweep (~7 min) ==" >&2
  : > /tmp/port-smoke.out
  for off in $(seq 0 300 2100); do
    php tools/smoke.php --chunk=300 --offset="$off" 2>/dev/null >> /tmp/port-smoke.out || true
  done
  read -r ok_cnt fatal_cnt missing_cnt dep_cnt <<< "$(
    python3 - <<'PY'
totals = {'ok': 0, 'fatal': 0, 'missing': 0, 'deprecations': 0}
for line in open('/tmp/port-smoke.out', errors='replace'):
    if not line.startswith('SUMMARY\t'):
        continue
    for field in line.strip().split('\t')[1:]:
        key, _, value = field.partition('=')
        if key in totals:
            totals[key] += int(value)
print(totals['ok'], totals['fatal'], totals['missing'], totals['deprecations'])
PY
  )"
  smoke_block="
**Class-load smoke** (\`tools/smoke.php\`): $ok_cnt load clean, $fatal_cnt fatal, $missing_cnt missing.
See the *Known-benign smoke results* section before treating a fatal as a regression.
"
else
  smoke_block="
**Class-load smoke**: not run in this refresh — run \`tools/port-status.sh --smoke\` to include it.
"
fi

stamp="$(date -u '+%Y-%m-%d %H:%M UTC')"

# ------------------------------------------------------------------- rewrite

BLOCK="$(
  cat <<EOF
<!-- STATUS:BEGIN (generated by tools/port-status.sh — do not hand-edit) -->
_Refreshed ${stamp}_

| | |
|---|---|
| Branch | \`$branch\` @ \`$head_sha\` — $head_subject |
| Uncommitted files | $dirty |
| Library files | $file_count |
| Syntax failures | $syntax_failures |
| PHPCompatibility ($TARGET_VERSION) | **$errors errors, $warnings warnings** ($total total) |
$smoke_block

### Remaining violations by sniff

| Count | Type | Sniff |
|---|---|---|
$top_sniffs

<!-- STATUS:END -->
EOF
)"

python3 - "$LEDGER" "$BLOCK" <<'PY'
import re
import sys

path, block = sys.argv[1], sys.argv[2]
src = open(path, encoding='utf-8').read()
pattern = re.compile(r'<!-- STATUS:BEGIN.*?<!-- STATUS:END -->', re.S)
if pattern.search(src):
    src = pattern.sub(lambda _: block, src)
else:
    src = src.rstrip() + '\n\n' + block + '\n'
open(path, 'w', encoding='utf-8').write(src)
PY

echo
echo "Updated $LEDGER"
echo "  syntax failures : $syntax_failures"
echo "  violations      : $errors errors, $warnings warnings ($total total)"
